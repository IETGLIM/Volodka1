#!/usr/bin/env node
/**
 * Import Ready Player Me NPC GLBs into the Volodka asset pipeline.
 *
 * Workflow:
 *   1. Create/export avatar on https://readyplayer.me/ (GLB, T-pose)
 *   2. Optional Blender cleanup + Mixamo animation retarget
 *   3. npm run assets:rpm-import -- --id npc_albert --file ~/Downloads/albert.glb
 *   4. npm run assets:validate
 *
 * Usage:
 *   npm run assets:rpm-import -- --list
 *   npm run assets:rpm-import -- --status
 *   npm run assets:rpm-import -- --id npc_albert --file ./albert.glb
 *   npm run assets:rpm-import -- --apply-all
 */

import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(ROOT, 'public');
const GENERATED_ON_DISK = path.join(ROOT, 'src/config/rpmNpcOnDisk.generated.ts');

function parseArgs(argv) {
  const args = { list: false, status: false, applyAll: false, id: null, file: null, help: false };
  for (let i = 2; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === '--list') args.list = true;
    else if (token === '--status') args.status = true;
    else if (token === '--apply-all') args.applyAll = true;
    else if (token === '--id') args.id = argv[++i] ?? null;
    else if (token === '--file') args.file = argv[++i] ?? null;
    else if (token === '--help' || token === '-h') args.help = true;
  }
  return args;
}

async function loadCatalog() {
  const modulePath = path.join(ROOT, 'src/config/rpmNpcCatalog.ts');
  return import(pathToFileURL(modulePath).href);
}

function publicFile(url) {
  return path.join(PUBLIC, url.replace(/^\//, ''));
}

function copyToPublic(sourcePath, publicUrl) {
  const dest = publicFile(publicUrl);
  mkdirSync(path.dirname(dest), { recursive: true });
  copyFileSync(sourcePath, dest);
  return dest;
}

function stageHeroLods(sourcePath, catalog) {
  const hero = catalog.RPM_NPC_CATALOG.find((e) => e.id === 'npc_volodka');
  if (!hero) return [];
  const staged = [];
  for (const url of catalog.RPM_HERO_LOD_URLS) {
    const dest = copyToPublic(sourcePath, url);
    staged.push(url);
    console.log(`  ✓ hero LOD → ${path.relative(ROOT, dest)}`);
  }
  return staged;
}

function regenerateOnDiskFile(onDiskUrls) {
  const sorted = [...new Set(onDiskUrls)].sort();
  const body = sorted.map((u) => `  '${u}',`).join('\n');
  const content = `/**
 * AUTO-GENERATED by scripts/rpm-npc-import.mjs — do not edit manually.
 * Registry of RPM NPC GLB public URLs confirmed on disk after import.
 * Empty until \`npm run assets:rpm-import\` stages avatars (Sprint 2 pipeline).
 * Regenerate: npm run assets:rpm-import -- --apply-all
 */
export const RPM_NPC_GLB_URLS_ON_DISK: readonly string[] = [
${body}
];
`;
  writeFileSync(GENERATED_ON_DISK, content, 'utf8');
  console.log(`\n✓ Updated ${path.relative(ROOT, GENERATED_ON_DISK)} (${sorted.length} on-disk URL(s))`);
}

function scanShippedOnDisk(catalog) {
  const shipped = [];
  for (const entry of catalog.RPM_NPC_CATALOG) {
    const pub = publicFile(entry.publicUrl);
    if (existsSync(pub)) {
      shipped.push(entry.publicUrl);
    }
  }
  if (existsSync(publicFile(catalog.RPM_HERO_LOD_URLS[0]))) {
    for (const url of catalog.RPM_HERO_LOD_URLS) {
      if (existsSync(publicFile(url))) shipped.push(url);
    }
  }
  return [...new Set(shipped)];
}

function importEntry(spec, sourcePath, catalog) {
  const destSource = path.join(ROOT, spec.sourceRelativePath);
  mkdirSync(path.dirname(destSource), { recursive: true });
  copyFileSync(sourcePath, destSource);
  console.log(`✓ Source → ${path.relative(ROOT, destSource)}`);

  if (spec.wire.kind === 'hero') {
    stageHeroLods(sourcePath, catalog);
    return [spec.publicUrl, ...catalog.RPM_HERO_LOD_URLS];
  }

  const dest = copyToPublic(sourcePath, spec.publicUrl);
  console.log(`✓ Public → ${path.relative(ROOT, dest)}`);
  return [spec.publicUrl];
}

function printHelp() {
  console.log(`
Ready Player Me NPC import — Volodka RPG

  npm run assets:rpm-import -- --list
  npm run assets:rpm-import -- --status
  npm run assets:rpm-import -- --id <catalog-id> --file <path-to.glb>
  npm run assets:rpm-import -- --apply-all

Generator: https://readyplayer.me/
Drop zone: assets-source/ai3dgen/npcs/npc_*.glb

Notes:
  • RPM requires user account — CI never downloads avatars.
  • --apply-all copies every npc_*.glb present in assets-source/ai3dgen/npcs/
  • Supersedes Khronos/Quaternius CC0 placeholders when files land on disk.
  • Mixamo animations: retarget in Blender after RPM export (see README).
`);
}

async function main() {
  const args = parseArgs(process.argv);
  if (args.help) {
    printHelp();
    return;
  }

  const catalog = await loadCatalog();

  if (args.list) {
    console.log('RPM NPC catalog (20 avatars):\n');
    for (const entry of catalog.RPM_NPC_CATALOG) {
      const alias = entry.aliasNote ? `  [${entry.aliasNote}]` : '';
      console.log(`  ${entry.id.padEnd(22)} → ${entry.npcId.padEnd(20)} ${entry.publicUrl}`);
      console.log(`    ${entry.title} — ${entry.description}${alias}`);
    }
    console.log('\nExport GLB from Ready Player Me → optional Blender → drop in assets-source/ai3dgen/npcs/');
    return;
  }

  if (args.status) {
    console.log('RPM NPC import status:\n');
    let onDisk = 0;
    for (const entry of catalog.RPM_NPC_CATALOG) {
      const sourcePath = path.join(ROOT, entry.sourceRelativePath);
      const publicPath = publicFile(entry.publicUrl);
      const hasSource = existsSync(sourcePath);
      const hasPublic = existsSync(publicPath);
      if (hasSource) onDisk += 1;
      const srcKb = hasSource ? ` ${(statSync(sourcePath).size / 1024).toFixed(0)} KB` : '';
      const pubKb = hasPublic ? ` ${(statSync(publicPath).size / 1024).toFixed(0)} KB` : '';
      console.log(
        `${hasPublic ? '✓' : '·'} public  ${hasSource ? '✓' : '·'} source  ${entry.id.padEnd(22)} → ${entry.npcId}`,
      );
      if (hasSource || hasPublic) {
        console.log(`    source: ${path.relative(ROOT, sourcePath)}${srcKb}`);
        console.log(`    public: ${entry.publicUrl}${pubKb}`);
      }
    }
    const onDiskMod = await import(pathToFileURL(GENERATED_ON_DISK).href);
    console.log(
      `\n  Source files on disk: ${onDisk}/${catalog.RPM_NPC_CATALOG.length} (${catalog.RPM_NPC_CATALOG.length - onDisk} pending)`,
    );
    console.log(`  On-disk registry URLs: ${onDiskMod.RPM_NPC_GLB_URLS_ON_DISK.length}`);
    return;
  }

  if (args.applyAll) {
    const npcDir = path.join(ROOT, 'assets-source/ai3dgen/npcs');
    if (!existsSync(npcDir)) {
      console.error(`Missing directory: ${path.relative(ROOT, npcDir)}`);
      process.exit(1);
    }
    const files = readdirSync(npcDir).filter((f) => f.startsWith('npc_') && f.endsWith('.glb'));
    if (files.length === 0) {
      console.error('No npc_*.glb files in assets-source/ai3dgen/npcs/');
      process.exit(1);
    }
    console.log(`Applying ${files.length} RPM source file(s)…\n`);
    const stagedUrls = [];
    for (const file of files.sort()) {
      const catalogId = file.replace(/\.glb$/i, '');
      const spec = catalog.getRpmNpcSpec(catalogId);
      if (!spec) {
        console.warn(`⚠ Skipping unknown file: ${file}`);
        continue;
      }
      const sourcePath = path.join(npcDir, file);
      console.log(`▶ ${catalogId} → ${spec.npcId}`);
      stagedUrls.push(...importEntry(spec, sourcePath, catalog));
    }
    const allOnDisk = scanShippedOnDisk(catalog);
    regenerateOnDiskFile(allOnDisk.length > 0 ? allOnDisk : stagedUrls);
    console.log('\n── Next ──');
    console.log('  npm run assets:validate');
    console.log('  npm run check');
    return;
  }

  if (!args.id || !args.file) {
    printHelp();
    process.exit(1);
  }

  const spec = catalog.getRpmNpcSpec(args.id);
  if (!spec) {
    console.error(`Unknown catalog id "${args.id}". Run with --list.`);
    process.exit(1);
  }

  const inputPath = path.resolve(args.file);
  if (!existsSync(inputPath)) {
    console.error(`File not found: ${inputPath}`);
    process.exit(1);
  }

  console.log(`Import ${spec.id} → ${spec.npcId} (${spec.publicUrl})\n`);
  importEntry(spec, inputPath, catalog);

  const onDiskMod = await import(pathToFileURL(GENERATED_ON_DISK).href);
  const merged = [...new Set([...onDiskMod.RPM_NPC_GLB_URLS_ON_DISK, ...scanShippedOnDisk(catalog)])];
  regenerateOnDiskFile(merged);

  console.log('\n── Next ──');
  console.log('  npm run assets:validate');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
