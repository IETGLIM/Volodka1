export function getPoemById(id: string): Poem | undefined {
  const canonical = POEMS.find((p) => p.id === id);
  if (canonical) return canonical;
  // Expansion fragments (not in canonical poem_1–35 corpus)
  return EXPANSION_POEM_STUBS.find((p) => p.id === id);
}

export function getPoemsByTheme(theme: string): Poem[] {
  return POEMS.filter((p) => p.themes.includes(theme));
}

export function getOrderedPoems(): Poem[] {
  return [...POEMS].sort((a, b) => a.order - b.order);
}

export function getMainPoems(): Poem[] {
  return POEMS.filter((p) => isMainPoemId(p.id)).sort((a, b) => a.order - b.order);
}

export function getHiddenPoems(): Poem[] {
  return POEMS.filter((p) => !isMainPoemId(p.id));
}

/** Dev-only: validate poem unlock nodes and unique IDs. Returns list of problems. */
export async function validatePoemUnlockNodes(): Promise<string[]> {
  const { loadAllNarrativePacks, getStoryNodesCache } = await import('./narrative/narrativePackRegistry');
  await loadAllNarrativePacks();
  const storyNodes = getStoryNodesCache();

  const problems: string[] = [];
  const seenIds = new Set<string>();
  for (const poem of POEMS) {
    if (seenIds.has(poem.id)) {
      problems.push(`duplicate poem id "${poem.id}"`);
    }
    seenIds.add(poem.id);
    if (!storyNodes[poem.unlocksAt]) {
      problems.push(`${poem.id} unlocksAt "${poem.unlocksAt}" not in STORY_NODES`);
    }
  }
  return problems;
}
