import type { Poem } from '@/shared/types/game';

function expansionPoem(
  id: string,
  title: string,
  order: number,
  unlocksAt: string,
  opts: {
    author?: string;
    themes: string[];
    intro: string;
    lines: string[];
  },
): Poem {
  return {
    id,
    title,
    author: opts.author ?? 'Неизвестный поэт кода',
    order,
    unlocksAt,
    themes: opts.themes,
    intro: opts.intro,
    bonus: true,
    lines: opts.lines,
  };
}

