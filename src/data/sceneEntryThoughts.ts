/* ─── Scene Entry Thoughts — Volodka's reactive inner monologue ───
 *
 * Enriched system: each scene can have first-visit thoughts branched by
 * karma / stress / story act, plus act-specific revisit thoughts that fire
 * once when re-entering a scene during a new story act. Thoughts are
 * recorded in the persistent journal (thoughtHistory) so the player can
 * re-read them later.
 *
 * Resolution order on scene:enter:
 *   1. If first ever visit → check highStress, then firstVisitByKarma, then firstVisit
 *   2. If revisit → check byAct[currentAct]; if not yet shown for this act, show it
 *   3. Otherwise → no thought (avoid spam)
 *
 * Tracking flags:
 *   `visited_thought_{sceneId}`           — first-visit thought shown
 *   `thought_act_{sceneId}_{actNumber}`   — act-specific revisit thought shown
 */

import type { SceneId } from '@/shared/types/game';

/* ─── Context passed to reactive thought selectors ─── */

export interface ThoughtContext {
  /** Player karma (0–100; high ≥ 65, low ≤ 30). */
  karma: number;
  /** Player stress (0–100; high ≥ 70). */
  stress: number;
  /** Player energy (0–100). */
  energy: number;
  /** Current story act (1–7). */
  currentAct: number;
  /** Player flags (story state, visit markers, etc.). */
  flags: Record<string, boolean>;
}

/** A thought can be a plain string or a function that reads game context. */
export type ThoughtText = string | ((ctx: ThoughtContext) => string);

/** Karma-branched first-visit variants. Neutral falls through to `firstVisit`. */
export interface KarmaBranchedThoughts {
  /** Shown when karma ≥ 65. */
  high?: ThoughtText;
  /** Shown when karma ≤ 30. */
  low?: ThoughtText;
}

export interface SceneThoughtConfig {
  /** Shown on first ever visit to this scene (fallback for neutral karma). */
  firstVisit: ThoughtText;
  /** Karma-branched first-visit variants (checked before `firstVisit`). */
  firstVisitByKarma?: KarmaBranchedThoughts;
  /** Shown on first visit when stress ≥ 70 (checked before karma branches). */
  highStress?: ThoughtText;
  /**
   * Act-specific revisit thoughts. Shown once when re-entering the scene
   * during a new story act (tracked via `thought_act_{sceneId}_{act}`).
   */
  byAct?: Partial<Record<number, ThoughtText>>;
}

/* ─── Helpers ─── */

const HIGH_KARMA = 65;
const LOW_KARMA = 30;
const HIGH_STRESS = 70;

/** Resolve a ThoughtText (string or function) to a concrete string. */
function resolve(text: ThoughtText, ctx: ThoughtContext): string {
  return typeof text === 'function' ? text(ctx) : text;
}

export interface ResolvedThought {
  text: string;
  /** Which tracking flag to set after showing. */
  flagToSet: string;
}

/**
 * Resolve which thought (if any) to show on entering a scene.
 * Returns `null` if no thought should be shown (e.g. same-act revisit
 * with no new act-specific line).
 */
export function resolveSceneThought(
  sceneId: SceneId,
  ctx: ThoughtContext,
): ResolvedThought | null {
  const config = SCENE_THOUGHTS[sceneId];
  if (!config) return null;

  const firstVisitFlag = `visited_thought_${sceneId}`;
  const isFirstVisit = !ctx.flags[firstVisitFlag];

  if (isFirstVisit) {
    // Priority: highStress → firstVisitByKarma → firstVisit
    if (ctx.stress >= HIGH_STRESS && config.highStress) {
      return { text: resolve(config.highStress, ctx), flagToSet: firstVisitFlag };
    }
    if (config.firstVisitByKarma) {
      if (ctx.karma >= HIGH_KARMA && config.firstVisitByKarma.high) {
        return { text: resolve(config.firstVisitByKarma.high, ctx), flagToSet: firstVisitFlag };
      }
      if (ctx.karma <= LOW_KARMA && config.firstVisitByKarma.low) {
        return { text: resolve(config.firstVisitByKarma.low, ctx), flagToSet: firstVisitFlag };
      }
    }
    return { text: resolve(config.firstVisit, ctx), flagToSet: firstVisitFlag };
  }

  // Revisit — check for act-specific thought
  if (config.byAct && config.byAct[ctx.currentAct]) {
    const actFlag = `thought_act_${sceneId}_${ctx.currentAct}`;
    if (!ctx.flags[actFlag]) {
      return { text: resolve(config.byAct[ctx.currentAct]!, ctx), flagToSet: actFlag };
    }
  }

  return null;
}

